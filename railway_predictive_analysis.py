def execute_pert_cpm(tasks_dict):
    """
    Ingests an Activity-on-Node dictionary and computes PERT expected durations,
    variances, and executes the CPM forward/backward passes to identify the critical path.
    """
    network = {}

    # PERT Calculations
    for node, data in tasks_dict.items():
        O, M, P = data['O'], data['M'], data['P']
        TE = (O + 4*M + P) / 6.0
        variance = ((P - O) / 6.0) ** 2
        network[node] = {
            'TE': TE, 'Var': variance, 'preds': data['preds'],
            'ES': 0.0, 'EF': 0.0, 'LS': float('inf'), 'LF': float('inf'), 'Slack': 0.0
        }

    # CPM Forward Pass
    for node in network:
        if not network[node]['preds']:
            network[node]['ES'] = 0.0
        else:
            network[node]['ES'] = max([network[p]['EF'] for p in network[node]['preds']])
        network[node]['EF'] = network[node]['ES'] + network[node]['TE']

    project_completion_time = max([data['EF'] for data in network.values()])

    # CPM Backward Pass
    for node in reversed(list(network.keys())):
        successors = [t for t, d in network.items() if node in d['preds']]
        if not successors:
            network[node]['LF'] = project_completion_time
        else:
            network[node]['LF'] = min([network[s]['LS'] for s in successors])
        network[node]['LS'] = network[node]['LF'] - network[node]['TE']
        network[node]['Slack'] = network[node]['LS'] - network[node]['ES']

    # Identify Critical Path and compute Project Standard Deviation
    critical_path = [node for node, d in network.items() if abs(d['Slack']) < 1e-5]
    project_variance = sum([network[node]['Var'] for node in critical_path])
    project_std = np.sqrt(project_variance)

    return project_completion_time, project_std, critical_path, network

