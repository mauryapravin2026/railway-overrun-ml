# PERT Schedule Computations
def run_pert(row):
    tasks = ['T1', 'T2', 'T3', 'T4', 'T5']
    te, var = {}, {}
    for t in tasks:
        te[t] = (row[f'{t}_O'] + 4*row[f'{t}_M'] + row[f'{t}_P']) / 6.0
        var[t] = ((row[f'{t}_P'] - row[f'{t}_O']) / 6.0) ** 2
    # Critical Path: T1 -> max(T2, T3) -> T4 -> T5
    crit_branch = 'T2' if te['T2'] > te['T3'] else 'T3'
    crit_tasks = ['T1', crit_branch, 'T4', 'T5']
    te_proj = sum(te[t] for t in crit_tasks)
    std_proj = np.sqrt(sum(var[t] for t in crit_tasks))
    z_score = (row['Target_Deadline_Weeks'] - te_proj) / std_proj
    prob = norm.cdf(z_score) * 100.0
    return pd.Series([te_proj, std_proj, prob, te_proj / 52.14],
                     index=['PERT_TE_Weeks', 'PERT_Std_Weeks', 'PERT_Prob_Pct', 'PERT_Predicted_Delay'])

pert_res = df.apply(run_pert, axis=1)
df = pd.concat([df, pert_res], axis=1)

