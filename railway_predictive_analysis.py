def assign_state(agency):
    agency = str(agency).lower()
    if 'east coast' in agency or 'ecor' in agency: return 'Odisha'
    elif 'east central' in agency or 'ecr' in agency or 'patna' in agency: return 'Bihar'
    elif 'south central' in agency or 'scr' in agency: return 'Telangana'
    elif 'north western' in agency or 'nwr' in agency: return 'Rajasthan'
    elif 'south western' in agency or 'swr' in agency or 'k-ride' in agency or 'karnataka' in agency: return 'Karnataka'
    elif 'western railway' in agency or 'wr' in agency: return 'Gujarat'
    elif 'north central' in agency or 'ncr' in agency or 'ner' in agency or 'north eastern' in agency: return 'Uttar Pradesh'
    elif 'central railway' in agency or 'cr' in agency or 'mrvc' in agency or 'mumbai' in agency or 'mridc' in agency: return 'Maharashtra'
    elif 'northeast frontier' in agency or 'nfr' in agency or 'northeast' in agency: return 'Assam'
    elif 'secr' in agency or 'south east central' in agency: return 'Chhattisgarh'
    elif 'eastern railway' in agency or 'er' in agency or 'south eastern' in agency or 'ser' in agency or 'kolkata' in agency: return 'West Bengal'
    elif 'northern' in agency or 'nr' in agency: return 'Punjab'
    else: return 'Madhya Pradesh'

